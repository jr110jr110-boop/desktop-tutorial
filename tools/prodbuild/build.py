FA = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")
TOKEN = re.compile(r"\d{4}/\d{2}/\d{2}|\d{1,2}:\d{2}|(?<![\d/])\d{2}/\d{2}(?![\d/])|[A-Za-z]+-(?:\{[a-z]+(?::\d+)?\}-?)+|\{[a-z]+(?::\d+)?\}(?:[-/.]?(?:\{[a-z]+(?::\d+)?\}|[A-Za-z]+))*|[A-Za-z][\w-]*\.(?:xlsx|csv|pdf|cmd)|(?<![\w])[A-Z]{2,4}-\d+|\d-[A-Za-z][A-Za-z0-9\\._-]*|(?<![\w])(?=[A-Za-z0-9.-]*\d)[A-Za-z][A-Za-z0-9]*(?:[-.][A-Za-z0-9]+)*")

def fa(text, wrap=None):
    text = text.replace("%", "٪")
    out, pos = [], 0
    for m in TOKEN.finditer(text):
        out.append(text[pos:m.start()].translate(FA))
        tok = m.group(0)
        if re.fullmatch(r"[\d:/]+", tok): tok = tok.translate(FA)
        out.append(wrap(tok) if wrap else tok)
        pos = m.end()
    out.append(text[pos:].translate(FA))
    return "".join(out)

def h(text):
    return fa(html.escape(text, quote=False), wrap=lambda t: '<bdi class="l" dir="ltr">%s</bdi>' % t)

def ltr(s):
    return re.sub(r"(?<![>\w])(M-\d\d)(?![\w<])", r'<bdi class="l" dir="ltr">\1</bdi>', s)

def plain(text):
    return fa(text)

