def mk(name, sheets):
    wb = openpyxl.Workbook(); first = True
    for title, header, rows, widths in sheets:
        ws = wb.active if first else wb.create_sheet()
        first = False
        ws.title = title; ws.sheet_view.rightToLeft = True
        ws.append(header)
        for r in rows: ws.append(r)
        for c in ws[1]:
            c.font = Font(name="B Zar", bold=True, size=12); c.fill = PatternFill("solid", fgColor="DDDDDD"); c.alignment = Alignment(horizontal="center", wrap_text=True)
        for row in ws.iter_rows(min_row=2):
            for c in row:
                c.font = Font(name="B Zar", size=12); c.alignment = Alignment(vertical="top", wrap_text=True)
                if isinstance(c.value, str): c.number_format = "@"
        for i, w in enumerate(widths): ws.column_dimensions[chr(65 + i)].width = w
        ws.freeze_panes = "A2"
    note = wb.create_sheet("توضیح")
    note.sheet_view.rightToLeft = True
    note.column_dimensions["A"].width = 110
    for line in ["فقط مرجع آزمون است؛ این فایل خودکار وارد برنامه نمی‌شود. مقدارها را دستی در صفحه‌های برنامه وارد کنید (راهنمای آزمون، بخش‌های S1 و S2).",
                 "همه کدها و عنوان‌ها آزمایشی‌اند و نام شخص در آن‌ها نیست. کد کالا از قالب کالای شرکت است ولی مصرف واقعی ندارد."]:
        note.append([line])
        note.cell(note.max_row, 1).font = Font(name="B Zar", size=12); note.cell(note.max_row, 1).alignment = Alignment(wrap_text=True, vertical="top")
    wb.save(D + name)

