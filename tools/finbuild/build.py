def fa(text, wrap=None):
    """Persian digits, separators; Latin codes (letters+digits) are kept as they are."""
    text = re.sub(r"(?<=\d)\.(?=\d)", "٫", text) if False else text
    text = text.replace("%", "٪")
    out, pos = [], 0
    for m in TOKEN.finditer(text):
        out.append(text[pos:m.start()].translate(FA))
        tok = m.group(0)
        out.append(wrap(tok) if wrap else tok)
        pos = m.end()
    out.append(text[pos:].translate(FA))
    return "".join(out)

def h(text):
    return fa(html.escape(text, quote=False), wrap=lambda t: '<bdi class="l" dir="ltr">%s</bdi>' % t)

def plain(text):
    return fa(text)

